package Day4;

public class EvenORodd {

	public static void main(String[] args) 
	{
		int a=10, b=5;
		if(a%2==0)
		{
				System.out.println("a (" + a + ") is Even Number");
		}	else 
		{
	            System.out.println("a (" + a + ") is an Odd Number");
		}
		if(b%2==1)
		{
				System.out.println("b (" + b + ") is Odd Number");
		}	else
		{
				System.out.println("b (" + b + ") is an Even Number");
        }
		
	}

}
