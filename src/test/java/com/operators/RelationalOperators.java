package com.operators;

public class RelationalOperators {

	public static void main(String[] args) {
		// Relational/Comparison Operators!!!! Primitive Datatypes and Numbers
		// >, >=, <, <=, !=, ==
		int number1 = 5;
		int number2 = 10;
		System.out.println(number1 > number2);
		System.out.println(number1 < number2);
		System.out.println(number1 == number2);
		System.out.println(number1 != number2);
		System.out.println(number1 >= number2);
		System.out.println(number1 <= number2);
	}

}
